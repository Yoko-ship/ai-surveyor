_EGOV_REGION_BASE = {
    "andijon": "region:ANDIJON", "buxoro": "region:BUXORO", "jizzax": "region:JIZZAX",
    "qashqadaryo": "region:QASHQADARYO", "navoiy": "region:NAVOIY", "namangan": "region:NAMANGAN",
    "samarqand": "region:SAMARQAND", "surxondaryo": "region:SURXANDARYO", "sirdaryo": "region:SIRDARYO",
    "toshkent": "region:TOSHKENT", "fargona": "region:FARG'ONA", "xorazm": "region:XORAZM",
}
_APOS = "‘’ʻʼ`´′ʹ'"


def egov_region(name: str) -> str:
    """
    Узбекское название региона в наборе data.egov.uz → ключ region:*.
    «Andijon», «Andijon viloyati» — область; «Andijon sh.» — город областного значения, НЕ регион ('');
    «Toshkent sh.» / «Toshkent shahri» — город Ташкент; «O'zbekiston Respublikasi» — республика.
    Районы («… tumani») и неизвестное — ''.
    """
    t = str(name or "").replace("\r", " ").replace("\n", " ").replace("*", " ").strip().lower()
    for a in _APOS:
        t = t.replace(a, "")
    t = t.replace("а", "a")                    # в наборах МВД встречается кириллическая «А»
    toks = t.split()
    if not toks:
        return ""
    if toks[0] in ("ozbekiston", "uzbekiston") or t.startswith("respublika buyicha"):
        return "total"
    if toks[0].startswith("qoraqalpog"):
        return "region:QORAQALPOG'ISTON RESPUBLIKASI" if " ".join(toks[1:]) in ("", "respublikasi") else ""
    base, rest = toks[0], " ".join(toks[1:]).rstrip(".")
    if base == "toshkent" and rest in ("sh", "shahri", "shaxri", "shahar"):
        return "region:TOSHKENT SHAHRI"
    if base in _EGOV_REGION_BASE and rest in ("", "viloyati", "vil", "viloyat"):
        return _EGOV_REGION_BASE[base]
    return ""


