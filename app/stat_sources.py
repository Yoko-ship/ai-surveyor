def _siat(ds_id, name, src_id, topic, period, unit, regions, purpose, limits=(), classes=()):
    return {
        "id": ds_id, "name": name, "source": SOURCE_STAT, "src_id": str(src_id),
        "page": _PAGE % topic, "data_url": SIAT_JSON % src_id,
        "period": period, "unit": unit, "regions": regions,
        "purpose": purpose, "limits": list(limits), "class_codes": list(classes),
    }


def _egov(ds_id, name, struct_id, period, unit, regions, purpose, limits=(), classes=(), egov=None):
    """egov — настройки разбора для наборов, у которых поля не «2026yilIIchorak»:
    {"annual_only": True} — брать только годовые столбцы (2014yil, 2014Y, 2024yanvardekabr);
    {"mode": "fx"} — курсы валют ЦБ (код, дата, курс). Без egov разбор прежний (набор emergencies)."""
    d = {
        "id": ds_id, "name": name, "source": SOURCE_EGOV, "src_id": struct_id,
        "page": EGOV_PAGE % struct_id, "data_url": EGOV_DATA % struct_id,
        "period": period, "unit": unit, "regions": regions,
        "purpose": purpose, "limits": list(limits), "class_codes": list(classes),
    }
    if egov is not None:
        d["egov"] = dict(egov)
    return d


