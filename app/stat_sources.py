def parse_siat(payload: str, ds: dict) -> Tuple[List[dict], dict]:
    """
    Разбирает JSON api.siat.stat.uz. Возвращает (записи, паспорт набора).
    Паспорт — то, что источник сам про себя написал: имя, периодичность,
    единица, дата последнего изменения. Единицу берём у источника, а не из реестра.
    """
    doc = json.loads(payload)
    if isinstance(doc, list):
        doc = doc[0] if doc else {}
    meta_rows = doc.get("metadata") or []
    meta = {m.get("name_ru", ""): m.get("value_ru") for m in meta_rows}
    passport = {
        "name": meta.get("Имя индикатора") or ds["name"],
        "period": meta.get("Периодичность") or ds["period"],
        "unit": meta.get("Единица измерения") or ds["unit"],
        "updated": meta.get("Дата последнего изменения"),
        "code": meta.get("Идентификационный номер индикатора (код)"),
    }
    unit = passport["unit"]
    out: List[dict] = []
    for row in doc.get("data") or []:
        code = str(row.get("Code", "")).strip()
        reg = region_key(code) if ds["regions"] else ""
        if ds["regions"] and not reg:
            continue                       # районы и города — в разрез не берём
        for col, val in row.items():
            per = norm_period(col)
            if per is None:
                continue
            try:
                v = None if val in (None, "", "-") else float(val)
            except (TypeError, ValueError):
                v = None
            out.append({
                "source": ds["source"], "dataset_id": ds["id"], "key": code or ds["id"],
                "region": reg, "period": per, "value": v, "unit": unit, "url": ds["page"],
            })
    return out, passport


def parse_egov(payload: str, ds: dict) -> Tuple[List[dict], dict]:
    """
    Разбирает JSON data.egov.uz: список плоских записей, где имена полей —
    это и есть периоды (например «2026yilIIchorak»). Периоды достаём из имён полей.
    """
    rows = json.loads(payload)
    if isinstance(rows, dict):
        rows = rows.get("result") or rows.get("data") or []
    if ds.get("egov") is not None:
        return _parse_egov_ext(rows, ds)
    out: List[dict] = []
    for row in rows or []:
        key = ""
        for f, v in row.items():
            if f.lower() == "id":
                continue
            if _egov_period(f) is None and not key:
                key = str(v)
        for f, v in row.items():
            per = _egov_period(f)
            if per is None:
                continue
            try:
                val = None if v in (None, "", "-") else float(str(v).replace(" ", "").replace(",", "."))
            except ValueError:
                val = None
            out.append({
                "source": ds["source"], "dataset_id": ds["id"], "key": key or f,
                "region": "", "period": per, "value": val, "unit": ds["unit"], "url": ds["page"],
            })
    return out, {"name": ds["name"], "period": ds["period"], "unit": ds["unit"],
                 "updated": None, "code": ds["src_id"]}


_UZ_MONTHS = {"yanvar": 1, "fevral": 2, "mart": 3, "aprel": 4, "may": 5, "iyun": 6, "iyul": 7,
              "avgust": 8, "sentabr": 9, "oktabr": 10, "noyabr": 11, "dekabr": 12}
_MONTH_RE = "|".join(sorted(_UZ_MONTHS, key=len, reverse=True))
# поля, которые не являются ни ключом строки, ни периодом
_EGOV_SKIP = {"id", "olchovbirligi", "ozgarishifoizda"}


def egov_period_ext(field: str):
    """
    Имя столбца набора data.egov.uz → (период, вид). Вид: 'year' (полный год),
    'ytd' (нарастающим итогом с начала года, неполный год), 'point' (на конец месяца),
    'quarter'. Не период — (None, None).
      2014yil / 2014Y / 2014Yil / 2014     → ('2014', 'year')
      2024yanvardekabr                      → ('2024', 'year')      январь–декабрь = год
      2024yanvarsentabr                     → ('2024-M01-M09', 'ytd')
      2024Dekabr                            → ('2024-M12', 'point')
      2026yilIIchorak                       → ('2026-Q2', 'quarter')
    """
    f = (field or "").strip()
    m = re.fullmatch(r"(\d{4})(?:yil|y)?", f, re.I)
    if m:
        return m.group(1), "year"
    m = re.fullmatch(r"(\d{4})yanvar(%s)" % _MONTH_RE, f, re.I)
    if m:
        mon = _UZ_MONTHS[m.group(2).lower()]
        if mon == 12:
            return m.group(1), "year"
        return "%s-M01-M%02d" % (m.group(1), mon), "ytd"
    m = re.fullmatch(r"(\d{4})(%s)" % _MONTH_RE, f, re.I)
    if m:
        return "%s-M%02d" % (m.group(1), _UZ_MONTHS[m.group(2).lower()]), "point"
    m = re.fullmatch(r"(\d{4})yil(I{1,3}|IV)chorak", f, re.I)
    if m:
        return "%s-Q%d" % (m.group(1), _ROMAN[m.group(2).upper()]), "quarter"
    return None, None


def _num(v) -> Optional[float]:
    try:
        s = str(v).replace(" ", "").replace(",", ".").strip()
        return None if s in ("", "-", "None", "null") else float(s)
    except ValueError:
        return None


def _parse_egov_ext(rows, ds: dict) -> Tuple[List[dict], dict]:
    """
    Разбор «широких» наборов data.egov.uz органа статистики и ЦБ: одна строка — регион или
    показатель, столбцы — периоды. Регион опознаётся по узбекскому названию (egov_region);
    районы и города областного значения отбрасываются. У регионального набора ключ строки —
    ключ региона, чтобы разные написания («Andijon» и «Andijon viloyati») не плодили строки.
    """
    opt = ds.get("egov") or {}
    out: List[dict] = []
    if opt.get("mode") == "fx":
        for row in rows or []:
            code, rate, day = row.get("G1"), _num(row.get("G4")), str(row.get("G5") or "")
            m = re.fullmatch(r"(\d{2})\.(\d{2})\.(\d{4})", day.strip())
            if not code or not m:
                continue
            out.append({"source": ds["source"], "dataset_id": ds["id"], "key": str(code).strip(),
                        "region": "", "period": "%s-%s-%s" % (m.group(3), m.group(2), m.group(1)),
                        "value": rate, "unit": ds["unit"], "url": ds["page"]})
        return out, {"name": ds["name"], "period": ds["period"], "unit": ds["unit"],
                     "updated": None, "code": ds["src_id"]}
    for row in rows or []:
        key = None
        for f, v in row.items():
            if f.lower() in _EGOV_SKIP or egov_period_ext(f)[0] is not None:
                continue
            key = " ".join(str(v).split())
            break
        if key is None:
            continue
        reg = ""
        if ds["regions"]:
            reg = egov_region(key)
            if not reg:
                continue                   # район, город областного значения, подзаголовок
            key = reg
        for f, v in row.items():
            per, kind = egov_period_ext(f)
            if per is None:
                continue
            if opt.get("annual_only") and kind != "year":
                continue
            out.append({"source": ds["source"], "dataset_id": ds["id"], "key": key, "region": reg,
                        "period": per, "value": _num(v), "unit": ds["unit"], "url": ds["page"]})
    # один и тот же (ключ, период) дважды — источник повторил строку; берём первую, не суммируем
    seen, uniq = set(), []
    for r in out:
        k = (r["key"], r["region"], r["period"])
        if k not in seen:
            seen.add(k)
            uniq.append(r)
    return uniq, {"name": ds["name"], "period": ds["period"], "unit": ds["unit"],
                  "updated": None, "code": ds["src_id"]}


_ROMAN = {"I": 1, "II": 2, "III": 3, "IV": 4}


def _egov_period(field: str) -> Optional[str]:
    """«2026yilIIchorak» → '2026-Q2'; «2025» → '2025'; иначе None."""
    m = re.fullmatch(r"(\d{4})yil(I{1,3}|IV)chorak", field or "", re.I)
    if m:
        return "%s-Q%d" % (m.group(1), _ROMAN[m.group(2).upper()])
    return norm_period(field)


