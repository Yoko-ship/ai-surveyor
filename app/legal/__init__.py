"""
«ИИ специалист по страхованию INSON»: мгновенные ответы на трёх языках (ru | uz | en).

Специалист отвечает по страхованию, практике, праву и рынку. Мини-приложение запрашивает
ИИ автоматически; сервер проверяет допуск к выбранному провайдеру. Ответ содержит данные,
отдельное объяснение ИИ и ссылки. Без доступа/при сбое модели источники остаются доступны.

Правовая ветка: личный кэш (до часа) → lex.uz → FAQ → известные пробелы → локальный индекс.
lex.uz — источник №1: сервер ищет по обезличенным ключевым словам, проверяет дословные цитаты,
сохраняет найденные тексты в STORAGE_DIR/library_live. Кэш страниц — до суток, ранее сохранённые
акты отмечены found_base. Временно недоступный поиск и ошибки модели не кэшируются в ответах.
FAQ и нормы получают объяснение только по предоставленным сведениям; без нормы ИИ не должен
придумывать реквизиты. Локальная справка не является проверкой актуальной редакции.
Системный промпт: app/legal/ai.py + app/llm_prompts/legal_guard.ru.txt + общая AI-политика.
LEX_LIVE=0 отключает сеть, но не локальные источники. Поле live показывает результат поиска,
ограничения и сбои; with_actuality добавляет сведения lawwatch об изменившихся локальных актах.

Три языка. Файл считается узбекским/английским по пометке в имени («… (uz).txt», «… (узб).txt»,
«… (en).txt»), иначе язык определяется по тексту (app/ingest.detect_language), по умолчанию ru.
Узбекская латиница пишется с разными апострофами (gʻ ‘ ’ ʼ ` '), поэтому и при индексации, и в
запросе апострофы снимаются: «sugʻurta», «sug'urta» и «sugurta» — одно и то же слово.
Если на языке вопроса текста акта в базе нет — отвечаем по-русски и честно пишем об этом в note.

Персональные данные. Текст вопроса НЕ сохраняется: в legal_questions идёт только отпечаток
(sha256), язык, источник ответа, уверенность и время. Этого хватает, чтобы увидеть частые вопросы
без ответа и отдать их юристу на пополнение FAQ.

Рынок (с 02.10.2026, app/market_expert.py): вопрос о страховом рынке (лидер, доля, убыточность, премии,
классы, регионы, рыночная ставка) отвечается ИЗ ДАННЫХ — market_stats (отчёты НАПП), company_financials,
docs/market_facts.json — с плашкой источника (файл отчёта и дата среза). Модель только пересказывает.
Память диалога: POST /legal/ask c session_id — последние 8 реплик в памяти процесса (2 часа),
уточнения «а по классу 8?» разрешаются по контексту. В базу текст реплик не пишется.
Индекс знаний: закон (law), тарифная политика INSON (company), обзоры рынка docs/Знания/Рынок (market),
заметки docs/*.md и docs/Знания/*.md (note); у цитаты source_kind и source_label.

Подключение (app/main.py): app.include_router(legal.router) — индекс собирается сам при первом
обращении и дособирается по mtime файлов; принудительно — POST /legal/reindex (администратор).

Устройство пакета (04.10.2026; прежние имена app.legal.* сохранены фасадом app/legal/_facade.py):
  intents.py      — словари распознавания вопросов (ru/uz/en), только данные;
  texts.py        — тексты и подписи ответа на трёх языках;
  parse.py        — нормализация, язык, чистка мусора выгрузки lex.uz и веб-форм, нарезка на юниты;
  cache.py        — кэш ответов, кэш весов слов, журнал вопросов (только отпечаток);
  index.py        — источники, обход каталогов, сборка FTS5-индекса по mtime;
  search_core.py  — поиск, ранжирование, дословные цитаты;
  faq.py          — FAQ специалиста и известные молчания закона;
  ai.py           — необязательный пересказ моделью;
  live.py         — обёртка над живым поиском app/legal_live.py;
  market.py       — вопросы о рынке и финансах страховщиков (бывший app/market_expert.py, он теперь фасад);
  memory.py       — память диалога;
  competitors.py  — ответ по документам конкурентов;
  answer.py       — ask(): лестница источников, части data/opinion, sources;
  api.py          — маршруты /legal/*.
"""
from . import _facade
from . import intents, texts, parse, cache, index, search_core, faq, ai, live, market, memory  # noqa: F401
from . import competitors, answer, api  # noqa: F401

